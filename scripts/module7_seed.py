"""Build, verify and upload the Module 7 seed: one synthetic day of TechHub production traffic.

Usage (from the repo root):
    uv run python scripts/module7_seed.py build     # regenerate the data files of workshop_modules/module_7/data/
    uv run python scripts/module7_seed.py verify    # regenerate in memory, compare with the committed files, print the answer key
    uv run python scripts/module7_seed.py upload    # optional, needs a LangSmith key in .env: put the seeded day in your workspace
    uv run python scripts/module7_seed.py upload --dry-run          # print what would be sent; makes no request
    uv run python scripts/module7_seed.py upload --project NAME     # send to this tracing project instead of M7_PROJECT

`build` and `verify` run offline: no model, no LangSmith, no network. The data is generated by
`utils/trace_seeding.py::generate_seed`, never recorded, and is byte-reproducible, so `verify`
fails (exit code 1) if a committed file differs from a fresh generation by a single byte.

`upload` is the only command that contacts LangSmith, and only without `--dry-run`. It does what
the upload cell of Module 7 Section 1 does (`utils/trace_upload.py::upload_seed`): it refuses to
upload a second time, never creates a project by name and never deletes anything. It exits with
code 0 when the seeded day is in the workspace and 1 otherwise. No lab needs it: every notebook
reads the seed from disk.
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from utils.trace_seeding import DATA, DATA_FILES, SEED_FILE, generate_seed, seed_files  # noqa: E402


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _shown(path: Path) -> str:
    """The path relative to the repo root when it lies inside the repo."""
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def _print_answers(answers: dict) -> None:
    """Print the answer key, one checker id per block."""
    print("\nAnswer key (workshop_modules/module_7/data/answers.json):")
    for key, value in answers.items():
        if key.startswith("_"):
            continue
        print(f"  {key}:")
        for field, item in value.items():
            print(f"    {field}: {json.dumps(item)}")


def build(args: argparse.Namespace) -> int:
    """Generate the seed and write the seven data files."""
    generated = generate_seed()
    out = Path(args.out) if args.out else DATA
    out.mkdir(parents=True, exist_ok=True)
    for name, data in seed_files(generated).items():
        (out / name).write_bytes(data)
        print(f"wrote {_shown(out / name)}  {len(data):,} bytes")
    counts = generated["meta"]["counts"]
    print(f"\n{counts['conversations']} conversations, {counts['traces']} traces, {counts['runs']:,} runs. Every design constant was asserted.")
    return 0


def verify(args: argparse.Namespace) -> int:
    """Regenerate the seed in memory and compare every data file with the committed bytes."""
    generated = generate_seed()
    fresh = seed_files(generated)
    folder = Path(args.data) if args.data else DATA
    different = []
    print(f"Comparing {len(DATA_FILES)} files in {_shown(folder)} with a fresh generation:")
    for name in DATA_FILES:
        path = folder / name
        if not path.exists():
            different.append(name)
            print(f"  MISSING    {name}")
        elif path.read_bytes() != fresh[name]:
            different.append(name)
            print(f"  DIFFERENT  {name}")
        else:
            print(f"  identical  {name}  {len(fresh[name]):,} bytes  sha256 {_sha256(fresh[name])[:16]}...")
    _print_answers(generated["answers"])
    limit = 5 * 1024 * 1024
    size = len(fresh[SEED_FILE])
    if size >= limit:
        different.append(f"{SEED_FILE} is {size:,} bytes, not under 5 MB")
    if different:
        print(f"\nFAILED: {', '.join(different)}. Run `uv run python scripts/module7_seed.py build` and review the diff.")
        return 1
    counts = generated["meta"]["counts"]
    print(f"\nOK: the {len(DATA_FILES)} data files are identical to a fresh generation "
          f"({counts['conversations']} conversations, {counts['traces']} traces, {counts['runs']:,} runs; seed file {size:,} bytes).")
    return 0


def upload(args: argparse.Namespace) -> int:
    """Upload the seeded day to the workspace of the LangSmith key in `.env`, or print what would be sent."""
    import os

    from dotenv import load_dotenv

    # Before the next import: the LangSmith client reads its settings from the environment.
    load_dotenv(REPO_ROOT / ".env")
    from utils.trace_seeding import load_seed
    from utils.trace_upload import resolve_destination, upload_seed

    seed = load_seed()
    if args.dry_run:
        upload_seed(seed, resolve_destination(False, project_name=args.project), dry_run=True)
        return 0
    api_key = (os.getenv("LANGSMITH_API_KEY") or "").strip()
    if not api_key or api_key.startswith("<"):
        print("No LangSmith API key is set, so nothing was sent. Put LANGSMITH_API_KEY in .env, or run "
              "`uv run python scripts/module7_connect_langsmith.py`. The labs also run without a key.")
        return 1
    destination = resolve_destination(True, project_name=args.project)
    seeded = upload_seed(seed, destination)
    if seeded:
        print(destination.navigation)
    return 0 if seeded else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build, verify and upload the Module 7 seed (build and verify are offline).")
    commands = parser.add_subparsers(dest="command", required=True)
    build_parser = commands.add_parser("build", help="generate the seed and write the data files")
    build_parser.add_argument("--out", help="write to this folder instead of workshop_modules/module_7/data/")
    build_parser.set_defaults(run=build)
    verify_parser = commands.add_parser("verify", help="regenerate and compare with the committed files")
    verify_parser.add_argument("--data", help="compare the files in this folder instead of workshop_modules/module_7/data/")
    verify_parser.set_defaults(run=verify)
    upload_parser = commands.add_parser("upload", help="put the seeded day in your LangSmith workspace (needs a key in .env)")
    upload_parser.add_argument("--project", help="tracing project to send to, instead of M7_PROJECT (default techhub-deep-agent-production); "
                                                 "TECHHUB_AGENT_ID is then ignored")
    upload_parser.add_argument("--dry-run", action="store_true", help="print the number of batches and feedback calls; make no request")
    upload_parser.set_defaults(run=upload)
    args = parser.parse_args(argv)
    return args.run(args)


if __name__ == "__main__":
    raise SystemExit(main())
